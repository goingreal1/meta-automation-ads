-- Journeys v2: a readable visit number, city/region, and a lookup so media buyers see ad/campaign names for visits they are allowed to see.
alter table public.site_sessions add column if not exists visit_no bigint generated by default as identity;
alter table public.site_sessions add column if not exists city text;
alter table public.site_sessions add column if not exists region text;
create index if not exists site_sessions_visit_no on public.site_sessions (visit_no);

create or replace function public.rv_names(p_ids text[]) returns table(meta_id text, name text, level text) language sql stable security definer set search_path to 'public' as $$
  select o.meta_id, o.name, o.level
  from learn_objects o
  join profiles me on me.id = auth.uid() and me.company_id = o.company_id
  join ad_accounts ac on ac.id = o.ad_account_id
  where o.meta_id = any(p_ids)
    and (me.role in ('owner','admin') or ac.media_buyer_id = me.media_buyer_id)
$$;
grant execute on function public.rv_names(text[]) to authenticated;
